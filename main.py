# OmniSolver 
# Программа для расчёта прочности конструкций

print("OmniSolver")

# 1. Выбор типа конструкции
print("Выберите тип конструкции:")
print("1 - Beam (Балка)")
print("2 - Bunker (Бункер)")
print("3 - Fence (Ограждение)")
print("4 - Other (Другое)")

choice = input("Введите номер: ")

# 2. Ввод данных
N = float(input("Введите усилие N (кН): "))
A = float(input("Введите площадь сечения A (см2): "))
R = float(input("Введите сопротивление стали R (кН/см2): "))

# 3. Расчёт по формуле N / (A * R) <= 1
result = N / (A * R)

# 4. Вывод результата
print("Результат расчёта:", round(result, 2))

if result <= 1:
    print("Вердикт: ПРОХОДИТ")
else:
    print("Вердикт: НЕ ПРОХОДИТ")